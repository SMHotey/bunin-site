# -*- coding: utf-8 -*-
"""Собирает data/glossary.json из проверенных по корпусу списков слов.

Источник — glossary-checked.json + glossary-checked2.json (см. check-glossary-forms*.py).
Берём только слова, которые реально встречаются в текстах библиотеки, и только точные
формы: иначе примеры из произведений будут ложными.
"""
import json

part1 = json.load(open('scripts/glossary/glossary-checked.json', encoding='utf-8'))
part2 = json.load(open('scripts/glossary/glossary-checked2.json', encoding='utf-8'))

# Омонимия: у слова в корпусе есть и современное значение, пример это подтвердить не может.
DROP = {
    'свет', 'гость', 'покой', 'язык', 'живот', 'прелесть', 'пошлый', 'подлый',
    'обыватель', 'вёдро', 'выя', 'рамена', 'куща', 'просфора', 'полати', 'ухват',
    'курень', 'волость', 'исправник', 'околица', 'стерня', 'брег', 'отрок', 'оный',
    'кумир', 'алчный', 'ликующий', 'киот', 'сорокоуст', 'кутья', 'пожня', 'бричка',
    'оброк', 'барщина',
}

# Группировка: реалии уезда и службы отделены от деревенского быта
UYEZD = {'уезд', 'губерния', 'земство', 'десятина', 'становой', 'мещанин', 'казённый', 'погост', 'изволок'}

groups = {
    'arhaizmy': {
        'id': 'arhaizmy',
        'title': 'Книжные архаизмы',
        'about': 'Высокая лексика, унаследованная от поэтической традиции XIX века. Бунин держится её сознательно: у него она не украшение, а способ удержать тон стиха там, где проза уже сказала бы грубее.',
        'words': [],
    },
    'ushershie-znacheniya': {
        'id': 'ushershie-znacheniya',
        'title': 'Устаревшие значения знакомых слов',
        'about': 'Слова, которые мы знаем, но у Бунина они значат другое: хлеб в зерне, а не каша; кладбище при церкви, а не усадьба; мера земли, а не десятая часть.',
        'words': [],
    },
    'realyi': {
        'id': 'realyi',
        'title': 'Деревенские реалии и усадебный быт',
        'about': 'Предметы, по которым видно, как устроен бунинский мир: гумно и ток, зипун и поддёвка, барчук и мещанин. Без них пейзаж читается как открытка, а не как место, где жили люди.',
        'words': [],
    },
    'cerkovnoe': {
        'id': 'cerkovnoe',
        'title': 'Церковный и обрядовый обиход',
        'about': 'Слова церковного круга, которые в прозе Бунина обозначают не веру как тему, а порядок дня: службу, поминовение, образа в углу.',
        'words': [],
    },
}

USHER = {'жито', 'мещанин', 'казённый', 'погост', 'десятина', 'изволок'}

seen = set()
for row in part1 + part2:
    w = row['w']
    if w in DROP or w in seen:
        continue
    if not row['forms']:
        continue
    seen.add(w)
    group = row['group']
    if group == 'ushershie-znacheniya' and w not in USHER:
        continue
    if w in USHER:
        group = 'ushershie-znacheniya'
    groups[group]['words'].append({'w': w, 'm': row['m'], 'forms': row['forms']})

groups['arhaizmy']['words'].sort(key=lambda x: x['w'])
for key in ('ushershie-znacheniya', 'realyi', 'cerkovnoe'):
    groups[key]['words'].sort(key=lambda x: x['w'])

data = {
    'intro': [
        'Словарь к стихам и прозе Бунина: слова, которые современный читатель пробегает, не заметив, что не понял. Здесь только те слова, которые действительно встречаются в текстах этой библиотеки, — и у каждого указаны точные формы, по которым его искали.',
        'Бунин словарно консервативен: он вырос на пушкинской норме и сознательно не принимал лексических новшеств символистов. Поэтому его архаизмы — не стилизация, а язык, на котором он думал; деревенские реалии — не экзотика, а вещи, которые он видел в Ельце и на хуторе Озёрки.',
        'Значения даны по смыслу в контексте бунинских текстов. Где слово знакомо, но у него устарело значение (жито, десятина, погост), это оговорено отдельно: подстановка современного смысла меняет смысл строки.',
    ],
    'groups': [groups[k] for k in ('arhaizmy', 'ushershie-znacheniya', 'realyi', 'cerkovnoe')],
}

json.dump(data, open('data/glossary.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('слов всего:', sum(len(g['words']) for g in data['groups']))
for g in data['groups']:
    print(' ', g['id'], len(g['words']), '—', ', '.join(x['w'] for x in g['words']))
