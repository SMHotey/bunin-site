out = []
for word, meaning, group, forms in CANDIDATES:
    hits = 0
    sample = None
    sample_work = None
    found_forms = set()
    for w, tokens in texts:
        for f in forms:
            c = tokens.count(f)
            if c:
                found_forms.add(f)
                hits += c
        if sample is None:
            for f in forms:
                idx = tokens.index(f) if f in tokens else -1
                if idx >= 0:
                    raw = (w.get('text') or '').split('\n')
                    for line in raw:
                        if re.search(r'(?<![а-яА-ЯёЁ])' + f + r'(?![а-яА-ЯёЁ])', line.lower().replace('ё', 'е')):
                            if 12 <= len(line.strip()) <= 120:
                                sample = line.strip()
                                sample_work = w.get('title')
                                break
                    break
    out.append({
        'w': word, 'm': meaning, 'group': group,
        'forms': [f for f in forms if f in found_forms],
        'occ': hits, 'sample': sample, 'sampleWork': sample_work,
    })

out.sort(key=lambda r: (r['group'], -r['occ']))
for r in out:
    print(f"{r['occ']:4d}  {r['group']:22s} {r['w']:12s} forms={len(r['forms'])}  ex={r['sample']!r} — {r['sampleWork']}")
print()
